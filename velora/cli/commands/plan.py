"""`velora plan` — AI-assisted assessment planning (fixed capability catalog)."""
from __future__ import annotations

import click

from ...ai.service import build_provider
from ...models.enums import PlanStepStatus
from ...planning import AIPlanner, HeuristicPlanner, PlanService
from ...planning import capabilities as caps
from ...utils import console
from ..helpers import (
    AUTH_HELP,
    app_ctx,
    echo_json,
    require_authorization,
    scope_manager_for,
)

_RISK_COLOR = {"low": "green", "medium": "yellow", "lab-only": "red"}
_STATUS_COLOR = {"PROPOSED": "yellow", "APPROVED": "green", "REJECTED": "red",
                 "EXECUTED": "cyan", "SKIPPED": "bright_black"}


@click.group()
def plan() -> None:
    """Generate, review, approve and execute assessment plans.

    A plan may only reference capabilities from Velora's fixed catalog. The planner
    cannot invent an action, and no step runs without human approval and a scope check.
    """


@plan.command("capabilities")
@click.option("--json", "as_json", is_flag=True)
def plan_capabilities(as_json):
    """List the fixed catalog a plan may draw from."""
    if as_json:
        echo_json({k: c.to_dict() for k, c in caps.CAPABILITIES.items()})
        return
    console.header(f"Assessment capability catalog ({len(caps.CAPABILITIES)})")
    console.table(
        [[c.key, c.title[:32],
          click.style(c.risk, fg=_RISK_COLOR.get(c.risk, "white")),
          "safe" if c.safe_mode else "active",
          "always" if c.key in caps.REQUIRES_EXPLICIT_REVIEW else "-"]
         for c in caps.CAPABILITIES.values()],
        ["KEY", "TITLE", "RISK", "MODE", "EXPLICIT REVIEW"])
    click.echo("\nA planner can only select and order these entries. Anything else it "
               "returns is discarded before the plan is stored.")


@plan.command("generate")
@click.option("--target", "target_arg", required=True)
@click.option("--planner", "planner_name", type=click.Choice(["heuristic", "ai"]),
              default="heuristic", show_default=True)
@click.option("--scan", "scan_id", default=None)
@click.option("--engagement", "engagement_id", default=None)
@click.option("--scope", multiple=True)
@click.option("--allow-private", is_flag=True)
@click.pass_context
def plan_generate(click_ctx, target_arg, planner_name, scan_id, engagement_id,
                  scope, allow_private):
    """Generate an assessment plan. Sends no requests."""
    app = app_ctx(click_ctx)
    target = app.repo.get_target(target_arg) or app.repo.get_target_by_name(target_arg)
    if target is None:
        raise click.ClickException(f"target not found: {target_arg}")

    planner = (AIPlanner(build_provider(app.settings.ai)) if planner_name == "ai"
               else HeuristicPlanner())
    sm = scope_manager_for(target.url, scope, allow_private, app.settings, max_requests=1)
    service = PlanService(app.repo)
    plan_obj, steps = service.generate(target, planner=planner, scope=sm,
                                       scan_id=scan_id, engagement_id=engagement_id)

    console.header(f"{plan_obj.title}  ({plan_obj.id})")
    click.echo(f"generated by: {plan_obj.generated_by}")
    click.echo(f"rationale   : {plan_obj.rationale[:200]}")
    console.header(f"Proposed steps ({len(steps)})")
    console.table(
        [[str(s.order_index + 1), s.capability,
          click.style(s.risk, fg=_RISK_COLOR.get(s.risk, "white")),
          "yes" if s.scope_ok else click.style("OUT OF SCOPE", fg="red"),
          s.reason[:46]] for s in steps],
        ["#", "CAPABILITY", "RISK", "IN SCOPE", "REASON"])
    click.echo("\nAll steps are PROPOSED. Review them, then:")
    click.echo(f"  velora plan review {plan_obj.id}")
    click.echo(f"  velora plan approve {plan_obj.id} --operator you")


@plan.command("review")
@click.argument("plan_id")
@click.option("--json", "as_json", is_flag=True)
@click.pass_context
def plan_review(click_ctx, plan_id, as_json):
    """Review a plan's steps in full, including permissions and expected evidence."""
    app = app_ctx(click_ctx)
    plan_obj = app.repo.get_plan(plan_id)
    if plan_obj is None:
        raise click.ClickException(f"plan not found: {plan_id}")
    steps = app.repo.list_plan_steps(plan_id)
    if as_json:
        echo_json({"plan": plan_obj.model_dump(), "steps": [s.model_dump() for s in steps]})
        return
    console.header(f"{plan_obj.title}  ({plan_obj.id})")
    click.echo(f"generated by {plan_obj.generated_by}; "
               f"approved by {plan_obj.approved_by or '(not approved)'}")
    for step in steps:
        console.header(f"{step.order_index + 1}. {step.title}  [{step.capability}]")
        click.echo(f"  status              : "
                   + click.style(step.status.value,
                                 fg=_STATUS_COLOR.get(step.status.value, "white")))
        click.echo(f"  reason              : {step.reason}")
        click.echo(f"  scope               : {step.target_scope}  "
                   + ("in scope" if step.scope_ok
                      else click.style(f"OUT OF SCOPE ({step.scope_reason})", fg="red")))
        click.echo(f"  required permission : {step.required_permission}")
        click.echo(f"  expected evidence   : {step.expected_evidence}")
        click.echo(f"  risk                : "
                   + click.style(step.risk, fg=_RISK_COLOR.get(step.risk, "white")))
        click.echo(f"  validation          : {step.validation_requirement}")
        capability = caps.get(step.capability)
        if capability:
            click.echo(f"  reproduce with      : {capability.cli}")


@plan.command("approve")
@click.argument("plan_id")
@click.option("--operator", required=True, help="Who is approving.")
@click.option("--step", "step_ids", multiple=True, help="Approve only these step ids.")
@click.pass_context
def plan_approve(click_ctx, plan_id, operator, step_ids):
    """Approve a plan (human action). Out-of-scope steps can never be approved."""
    app = app_ctx(click_ctx)
    try:
        approved = PlanService(app.repo).approve(plan_id, operator,
                                                 step_ids=list(step_ids) or None)
    except ValueError as exc:
        raise click.ClickException(str(exc)) from exc
    console.ok(f"approved {len(approved)} step(s) on {plan_id}")
    for step in approved:
        click.echo(f"  {step.capability}  ({step.risk})")
    rejected = [s for s in app.repo.list_plan_steps(plan_id)
                if s.status == PlanStepStatus.REJECTED]
    if rejected:
        console.warn(f"{len(rejected)} step(s) refused:")
        for step in rejected:
            click.echo(f"  {step.capability}: {step.result_summary or step.scope_reason}")


@plan.command("execute")
@click.argument("plan_id")
@click.option("--operator", default="")
@click.option("--scope", multiple=True)
@click.option("--allow-private", is_flag=True)
@click.option("--dry-run", is_flag=True, help="Show what would run without running it.")
@click.option("--i-am-authorized", "authorized", is_flag=True, help=AUTH_HELP)
@click.pass_context
def plan_execute(click_ctx, plan_id, operator, scope, allow_private, dry_run, authorized):
    """Execute the APPROVED steps of a plan, re-checking scope immediately beforehand."""
    app = app_ctx(click_ctx)
    plan_obj = app.repo.get_plan(plan_id)
    if plan_obj is None:
        raise click.ClickException(f"plan not found: {plan_id}")
    target = app.repo.get_target(plan_obj.target_id)
    if target is None:
        raise click.ClickException(f"target not found: {plan_obj.target_id}")

    service = PlanService(app.repo)
    sm = scope_manager_for(target.url, scope, allow_private, app.settings, max_requests=1)
    runnable, blocked = service.executable_steps(plan_id, sm)

    console.header(f"Execution plan for {plan_id}")
    if blocked:
        console.warn("steps that will NOT run:")
        for reason in blocked:
            click.echo(f"  - {reason}")
    if not runnable:
        console.warn("no approved, in-scope steps to execute")
        return

    console.table([[s.capability, s.risk, caps.get(s.capability).cli if caps.get(s.capability)
                    else ""] for s in runnable],
                  ["CAPABILITY", "RISK", "COMMAND"])

    if dry_run:
        click.echo("\n--dry-run: nothing was executed.")
        return

    require_authorization(authorized)
    # Velora executes plan steps by invoking its own capabilities. Each capability is a
    # first-class command with its own scope gate; the planner never shells out.
    from ._plan_exec import execute_step

    for step in runnable:
        console.header(f"Executing {step.capability}")
        summary = execute_step(app, step, target, scope, allow_private, operator)
        service.mark_executed(step, summary)
        click.echo(f"  -> {summary}")


@plan.command("list")
@click.pass_context
def plan_list(click_ctx):
    """List assessment plans."""
    app = app_ctx(click_ctx)
    plans = app.repo.list_plans()
    if not plans:
        console.warn("no plans yet — `velora plan generate --target ...`")
        return
    console.table(
        [[p.id, p.title[:36], p.generated_by, p.approved_by or "-",
          str(len(app.repo.list_plan_steps(p.id)))] for p in plans],
        ["ID", "TITLE", "GENERATED BY", "APPROVED BY", "STEPS"])
